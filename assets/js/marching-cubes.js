  function extract(field, nx, ny, nz, opts) {
    opts = opts || {};
    var iso = opts.iso || 0;
    var ox = 0, oy = 0, oz = 0;
    if (opts.origin) { ox = opts.origin[0]; oy = opts.origin[1]; oz = opts.origin[2]; }
    var sx = 1, sy = 1, sz = 1;
    if (typeof opts.step === 'number') { sx = sy = sz = opts.step; }
    else if (opts.step) { sx = opts.step[0]; sy = opts.step[1]; sz = opts.step[2]; }

    var verts = [];                 // flat xyz
    var faces = [];
    var edgeCache = new Map();      // grid-edge key -> vertex index
    var nxy = nx * ny;

    /* Vertex on the grid edge starting at corner (i,j,k) along axis, welded. */
    function edgeVertex(i, j, k, axis, v0, v1) {
      var key = (i + nx * (j + ny * k)) * 3 + axis;
      var idx = edgeCache.get(key);
      if (idx !== undefined) return idx;
      var t = (iso - v0) / (v1 - v0);
      if (!isFinite(t)) t = 0.5;
      else if (t < 0) t = 0; else if (t > 1) t = 1;
      var x = i, y = j, z = k;
      if (axis === 0) x += t; else if (axis === 1) y += t; else z += t;
      idx = verts.length / 3;
      verts.push(ox + x * sx, oy + y * sy, oz + z * sz);
      edgeCache.set(key, idx);
      return idx;
    }

    var val = new Float64Array(8);
    var eidx = new Int32Array(12);
    for (var k = 0; k < nz - 1; k++) {
      for (var j = 0; j < ny - 1; j++) {
        var base = nx * (j + ny * k);
        for (var i = 0; i < nx - 1; i++) {
          var cube = 0;
          for (var c = 0; c < 8; c++) {
            var co = CORNER[c];
            var v = field[base + i + co[0] + nx * co[1] + nxy * co[2]];
            val[c] = v;
            if (v < iso) cube |= 1 << c;
          }
          if (cube === 0 || cube === 255) continue;
          var tris = TRI[cube];
          for (var e = 0; e < 12; e++) eidx[e] = -1;
          for (var t3 = 0; t3 < tris.length; t3 += 3) {
            for (var q = 0; q < 3; q++) {
              var e2 = tris[t3 + q];
              if (eidx[e2] === -1) {
                var ed = EDGE[e2];
                var bc = CORNER[ed[2]];
                eidx[e2] = edgeVertex(i + bc[0], j + bc[1], k + bc[2], ed[3],
                                      val[ed[2]], val[ed[0] === ed[2] ? ed[1] : ed[0]]);
              }
            }
            /* Table winding faces the inside; flip for outward normals
               under the "below iso = inside" convention. */
            faces.push(eidx[tris[t3]], eidx[tris[t3 + 2]], eidx[tris[t3 + 1]]);
          }
        }
      }
    }
    return { vertices: new Float32Array(verts), faces: new Uint32Array(faces) };
  }

  globalThis.MarchingCubes = { extract: extract };
